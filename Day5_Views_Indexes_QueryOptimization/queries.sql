SELECT COUNT(*) AS total_orders
FROM orders;

-- ==========================================
-- VIEW 1 : Delivered Orders View
-- Purpose : Show only delivered orders
-- ==========================================

CREATE VIEW delivered_orders AS
SELECT *
FROM orders
WHERE status = 'Delivered';

-- Check Delivered Orders Count
SELECT COUNT(*) AS delivered_orders
FROM delivered_orders;

-- ==========================================
-- VIEW 2 : State Revenue View
-- Purpose : Revenue generated by each state
-- ==========================================

CREATE VIEW state_revenue AS
SELECT state,
       SUM(total) AS revenue
FROM orders
GROUP BY state;

-- Top Revenue States Query
SELECT *
FROM state_revenue
ORDER BY revenue DESC
LIMIT 10;

-- ==========================================
-- VIEW 3 : Product Revenue View
-- Purpose : Revenue generated by each product
-- ==========================================

CREATE VIEW product_revenue AS
SELECT product_name,
       SUM(total) AS revenue
FROM orders
GROUP BY product_name;

-- Product Revenue Ranking Query
SELECT *
FROM product_revenue
ORDER BY revenue DESC;

-- ==========================================
-- INDEX 1 : State Index
-- Purpose : Faster search by state
-- ==========================================

CREATE INDEX idx_state
ON orders(state);

-- ==========================================
-- INDEX 2 : Status Index
-- Purpose : Faster search by status
-- ==========================================

CREATE INDEX idx_status
ON orders(status);

-- ==========================================
-- INDEX 3 : Composite Index
-- Purpose : Faster search using state + status
-- ==========================================

CREATE INDEX idx_state_status
ON orders(state, status);

